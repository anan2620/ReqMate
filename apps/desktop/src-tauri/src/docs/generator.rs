use std::path::Path;

use crate::models::collection::RequestFile;
use crate::storage::collection;

use super::DocsFormat;

struct DocRequest {
    folder: String,
    request: RequestFile,
}

/// A collection and every request found inside it.
struct CollectionDocs {
    name: String,
    requests: Vec<DocRequest>,
}

pub fn generate_docs(collection_path: &str, format: &DocsFormat) -> Result<String, String> {
    let docs = load_collection(collection_path)?;

    if docs.requests.is_empty() {
        return Err("No requests found in collection".to_string());
    }

    let title = docs.name.clone();
    Ok(render(&title, &[docs], format))
}

/// Documentation across several collections at once. A single path keeps the
/// original single-collection layout; more than one gets a combined document
/// with a section (and TOC group) per collection.
pub fn generate_docs_multi(
    collection_paths: &[String],
    format: &DocsFormat,
) -> Result<String, String> {
    let mut loaded: Vec<CollectionDocs> = Vec::new();

    for path in collection_paths {
        let docs = load_collection(path)?;
        if !docs.requests.is_empty() {
            loaded.push(docs);
        }
    }

    if loaded.is_empty() {
        return Err("No requests found in the selected collections".to_string());
    }

    if loaded.len() == 1 {
        let only = &loaded[0];
        return Ok(render(&only.name, &loaded, format));
    }

    Ok(render("API Documentation", &loaded, format))
}

fn render(title: &str, collections: &[CollectionDocs], format: &DocsFormat) -> String {
    let multi = collections.len() > 1;
    match format {
        DocsFormat::Html => generate_html(title, collections, multi),
        DocsFormat::Markdown => generate_markdown(title, collections, multi),
    }
}

fn load_collection(collection_path: &str) -> Result<CollectionDocs, String> {
    let path = Path::new(collection_path);
    let mut requests: Vec<DocRequest> = Vec::new();

    walk_requests(path, path, "", &mut requests)?;

    let name = path
        .file_name()
        .map(|n| n.to_string_lossy().to_string())
        .unwrap_or_else(|| "API Documentation".to_string());

    Ok(CollectionDocs { name, requests })
}

fn walk_requests(
    root: &Path,
    dir: &Path,
    folder_name: &str,
    requests: &mut Vec<DocRequest>,
) -> Result<(), String> {
    if !dir.exists() || !dir.is_dir() {
        return Ok(());
    }

    for entry in std::fs::read_dir(dir).map_err(|e| format!("Read dir error: {e}"))? {
        let entry = entry.map_err(|e| format!("Dir entry error: {e}"))?;
        let path = entry.path();

        if path.is_dir() {
            let name = path
                .file_name()
                .map(|n| n.to_string_lossy().to_string())
                .unwrap_or_default();

            // Skip hidden dirs
            if name.starts_with('.') {
                continue;
            }

            let sub_folder = if folder_name.is_empty() {
                name
            } else {
                format!("{folder_name}/{name}")
            };
            walk_requests(root, &path, &sub_folder, requests)?;
        } else if path
            .extension()
            .map(|e| e == "yaml" || e == "yml")
            .unwrap_or(false)
        {
            // Skip folder config and hidden files
            let fname = path
                .file_name()
                .map(|n| n.to_string_lossy().to_string())
                .unwrap_or_default();
            if fname.starts_with('_') || fname.starts_with('.') {
                continue;
            }

            if let Ok(request) = collection::read_request(&path) {
                requests.push(DocRequest {
                    folder: folder_name.to_string(),
                    request,
                });
            }
        }
    }

    Ok(())
}

// ── Markdown ────────────────────────────────────────────────────────────────

fn generate_markdown(title: &str, collections: &[CollectionDocs], multi: bool) -> String {
    let mut md = String::new();
    md.push_str(&format!("# {title}\n\n"));
    md.push_str(&format!(
        "*Generated by ReqMate on {}*\n\n",
        chrono::Utc::now().format("%Y-%m-%d %H:%M UTC")
    ));

    if multi {
        let names: Vec<String> = collections
            .iter()
            .map(|c| format!("{} ({})", c.name, c.requests.len()))
            .collect();
        md.push_str(&format!("**Collections:** {}\n\n", names.join(" · ")));
    }

    md.push_str("---\n\n");

    for collection in collections {
        if multi {
            md.push_str(&format!("## {}\n\n", collection.name));
            // Collection → h3 folders → h4 requests keeps the nesting readable
            write_markdown_requests(&mut md, &collection.requests, 3);
        } else {
            write_markdown_requests(&mut md, &collection.requests, 2);
        }
    }

    md
}

fn write_markdown_requests(md: &mut String, requests: &[DocRequest], base_level: usize) {
    let folder_hashes = "#".repeat(base_level);
    let request_hashes = "#".repeat(base_level + 1);

    // Group by folder
    let mut current_folder = String::new();

    for doc in requests {
        if doc.folder != current_folder {
            current_folder = doc.folder.clone();
            if !current_folder.is_empty() {
                md.push_str(&format!("{folder_hashes} {}\n\n", current_folder));
            }
        }

        let req = &doc.request;
        let method = format!("{:?}", req.method).to_uppercase();

        md.push_str(&format!("{request_hashes} {}\n\n", request_title(req)));
        md.push_str(&format!("`{method}` `{}`\n\n", req.url));

        if let Some(desc) = &req.description {
            if !desc.is_empty() {
                md.push_str(&format!("{desc}\n\n"));
            }
        }

        // Headers
        if !req.headers.is_empty() {
            md.push_str("**Headers:**\n\n");
            md.push_str("| Header | Value |\n|--------|-------|\n");
            for (k, v) in &req.headers {
                md.push_str(&format!("| `{k}` | `{v}` |\n"));
            }
            md.push('\n');
        }

        // Query params
        if let Some(params) = &req.params {
            if !params.is_empty() {
                md.push_str("**Query Parameters:**\n\n");
                md.push_str("| Parameter | Value |\n|-----------|-------|\n");
                for (k, v) in params {
                    md.push_str(&format!("| `{k}` | `{v}` |\n"));
                }
                md.push('\n');
            }
        }

        // Body
        if let Some(body) = &req.body {
            if !body.content.is_empty() {
                md.push_str(&format!("**Body** (`{}`):\n\n", body.body_type));
                md.push_str("```json\n");
                md.push_str(&body.content);
                if !body.content.ends_with('\n') {
                    md.push('\n');
                }
                md.push_str("```\n\n");
            }
        }

        md.push_str("---\n\n");
    }
}

// ── HTML ────────────────────────────────────────────────────────────────────

fn generate_html(title: &str, collections: &[CollectionDocs], multi: bool) -> String {
    let mut html = String::new();

    html.push_str("<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n");
    html.push_str("<meta charset=\"UTF-8\">\n");
    html.push_str("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1.0\">\n");
    html.push_str(&format!("<title>{title} — API Docs</title>\n"));
    html.push_str("<style>\n");
    html.push_str(CSS_STYLES);
    html.push_str("</style>\n</head>\n<body>\n");

    html.push_str(&format!("<h1>{}</h1>\n", html_escape(title)));
    html.push_str(&format!(
        "<p class=\"meta\">Generated by ReqMate on {}</p>\n",
        chrono::Utc::now().format("%Y-%m-%d %H:%M UTC")
    ));

    // TOC — one group per collection when there is more than one
    html.push_str("<nav class=\"toc\"><h2>Endpoints</h2>\n");
    for (ci, collection) in collections.iter().enumerate() {
        if multi {
            html.push_str(&format!(
                "<div class=\"toc-group\"><h3>{}</h3><ul>\n",
                html_escape(&collection.name)
            ));
        } else {
            html.push_str("<ul>\n");
        }
        for (i, doc) in collection.requests.iter().enumerate() {
            write_toc_item(&mut html, doc, &format!("req-{ci}-{i}"));
        }
        html.push_str("</ul>\n");
        if multi {
            html.push_str("</div>\n");
        }
    }
    html.push_str("</nav>\n");

    for (ci, collection) in collections.iter().enumerate() {
        if multi {
            html.push_str("<section class=\"collection\">\n");
            html.push_str(&format!(
                "<h2 class=\"collection-title\">{}</h2>\n",
                html_escape(&collection.name)
            ));
        }

        let mut current_folder = String::new();
        for (i, doc) in collection.requests.iter().enumerate() {
            if doc.folder != current_folder {
                current_folder = doc.folder.clone();
                if !current_folder.is_empty() {
                    if multi {
                        html.push_str(&format!(
                            "<p class=\"folder-label\">{}</p>\n",
                            html_escape(&current_folder)
                        ));
                    } else {
                        html.push_str(&format!(
                            "<h2 class=\"folder\">{}</h2>\n",
                            html_escape(&current_folder)
                        ));
                    }
                }
            }

            write_endpoint(&mut html, doc, &format!("req-{ci}-{i}"));
        }

        if multi {
            html.push_str("</section>\n");
        }
    }

    html.push_str("<footer>Generated by <a href=\"https://reqmate.dev\">ReqMate</a></footer>\n");
    html.push_str("</body>\n</html>\n");
    html
}

/// Requests normally carry a human name; fall back to the URL so a block is
/// never rendered with an empty heading.
fn request_title(req: &RequestFile) -> &str {
    if req.name.trim().is_empty() {
        &req.url
    } else {
        &req.name
    }
}

fn write_toc_item(html: &mut String, doc: &DocRequest, id: &str) {
    let method = format!("{:?}", doc.request.method).to_uppercase();
    let folder_prefix = if doc.folder.is_empty() {
        String::new()
    } else {
        format!("{} / ", doc.folder)
    };
    html.push_str(&format!(
        "<li><a href=\"#{id}\"><span class=\"method method-{m}\">{method}</span> {folder_prefix}{}</a></li>\n",
        html_escape(&doc.request.name),
        m = method.to_lowercase()
    ));
}

fn write_endpoint(html: &mut String, doc: &DocRequest, id: &str) {
    let req = &doc.request;
    let method = format!("{:?}", req.method).to_uppercase();

    html.push_str(&format!("<section id=\"{id}\" class=\"endpoint\">\n"));
    html.push_str(&format!(
        "<h3><span class=\"method method-{m}\">{method}</span> {title}</h3>\n",
        title = html_escape(request_title(req)),
        m = method.to_lowercase()
    ));
    html.push_str(&format!(
        "<p class=\"url\"><code>{}</code></p>\n",
        html_escape(&req.url)
    ));

    if let Some(desc) = &req.description {
        if !desc.is_empty() {
            html.push_str(&format!("<p class=\"desc\">{}</p>\n", html_escape(desc)));
        }
    }

    // Headers
    if !req.headers.is_empty() {
        html.push_str("<h4>Headers</h4>\n<table><thead><tr><th>Header</th><th>Value</th></tr></thead><tbody>\n");
        for (k, v) in &req.headers {
            html.push_str(&format!(
                "<tr><td><code>{}</code></td><td><code>{}</code></td></tr>\n",
                html_escape(k),
                html_escape(v)
            ));
        }
        html.push_str("</tbody></table>\n");
    }

    // Params
    if let Some(params) = &req.params {
        if !params.is_empty() {
            html.push_str("<h4>Query Parameters</h4>\n<table><thead><tr><th>Parameter</th><th>Value</th></tr></thead><tbody>\n");
            for (k, v) in params {
                html.push_str(&format!(
                    "<tr><td><code>{}</code></td><td><code>{}</code></td></tr>\n",
                    html_escape(k),
                    html_escape(v)
                ));
            }
            html.push_str("</tbody></table>\n");
        }
    }

    // Body
    if let Some(body) = &req.body {
        if !body.content.is_empty() {
            html.push_str(&format!(
                "<h4>Request Body <span class=\"body-type\">({})</span></h4>\n",
                html_escape(&body.body_type)
            ));
            html.push_str(&format!(
                "<pre><code>{}</code></pre>\n",
                html_escape(&body.content)
            ));
        }
    }

    html.push_str("</section>\n");
}

fn html_escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

