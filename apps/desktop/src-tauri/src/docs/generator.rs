#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;
    use std::path::PathBuf;

    struct Fixture {
        root: PathBuf,
    }

    impl Fixture {
        fn new(tag: &str) -> Self {
            let root = std::env::temp_dir()
                .join(format!("reqmate-docs-test-{tag}-{}", std::process::id()));
            let _ = fs::remove_dir_all(&root);
            fs::create_dir_all(&root).expect("create fixture dir");
            Fixture { root }
        }

        fn collection(&self, name: &str, files: &[(&str, &str)]) -> String {
            let dir = self.root.join(name);
            fs::create_dir_all(&dir).expect("create collection");
            for (file, contents) in files {
                let path = dir.join(file);
                if let Some(parent) = path.parent() {
                    fs::create_dir_all(parent).expect("create sub folder");
                }
                fs::write(path, contents).expect("write request");
            }
            dir.to_string_lossy().to_string()
        }
    }

    impl Drop for Fixture {
        fn drop(&mut self) {
            let _ = fs::remove_dir_all(&self.root);
        }
    }

    const LIST: &str =
        "name: List customers\nmethod: GET\nurl: https://api.example.com/customers\n";
    const CREATE: &str = "name: Create order\nmethod: POST\nurl: https://api.example.com/orders\n";

    #[test]
    fn single_collection_keeps_original_layout() {
        let fx = Fixture::new("single");
        let path = fx.collection("Payments", &[("list.yaml", LIST)]);

        let md = generate_docs(&path, &DocsFormat::Markdown).unwrap();
        assert!(
            md.starts_with("# Payments"),
            "title should be the collection name"
        );
        // The request name is the heading; method + URL sit on their own line
        assert!(md.contains("### List customers"));
        assert!(md.contains("`GET` `https://api.example.com/customers`"));

        let html = generate_docs(&path, &DocsFormat::Html).unwrap();
        assert!(html.contains("<title>Payments — API Docs</title>"));
        assert!(
            html.contains("<h3><span class=\"method method-get\">GET</span> List customers</h3>")
        );
        assert!(
            html.contains("<p class=\"url\"><code>https://api.example.com/customers</code></p>")
        );
        assert!(
            html.contains("<h3><span class=\"method method-get\">GET</span> List customers</h3>")
        );
        assert!(
            html.contains("<p class=\"url\"><code>https://api.example.com/customers</code></p>")
        );
        assert!(!html.contains("<h2 class=\"collection-title\">"));
    }

    #[test]
    fn multi_collection_includes_every_collection() {
        let fx = Fixture::new("multi");
        let a = fx.collection("Payments", &[("list.yaml", LIST)]);
        let b = fx.collection(
            "Orders",
            &[("create.yaml", CREATE), ("nested/get.yaml", LIST)],
        );

        let md = generate_docs_multi(&vec![a.clone(), b.clone()], &DocsFormat::Markdown).unwrap();
        assert!(md.contains("## Payments"));
        assert!(md.contains("## Orders"));
        assert!(md.contains("### Create order"));
        assert!(md.contains("`POST` `https://api.example.com/orders`"));
        // Nested folders are still grouped inside their collection
        assert!(md.contains("### nested"));

        let html = generate_docs_multi(&vec![a, b], &DocsFormat::Html).unwrap();
        assert!(html.contains("<h2 class=\"collection-title\">Payments</h2>"));
        assert!(html.contains("Payments"));
        assert!(html.contains("Orders"));
        assert!(html.contains("req-0-0"));
        assert!(html.contains("req-1-1"));
    }

    #[test]
    fn multi_collection_skips_empty_and_falls_back_to_single() {
        let fx = Fixture::new("fallback");
        let a = fx.collection("Only", &[("list.yaml", LIST)]);
        let empty = fx.collection("Empty", &[]);

        let md = generate_docs_multi(&vec![a, empty], &DocsFormat::Markdown).unwrap();
        assert!(
            md.starts_with("# Only"),
            "a single non-empty collection renders like before"
        );
    }

    #[test]
    fn empty_selection_is_an_error() {
        let fx = Fixture::new("empty");
        let empty = fx.collection("Empty", &[]);
        assert!(generate_docs_multi(&vec![empty], &DocsFormat::Html).is_err());
    }
}
